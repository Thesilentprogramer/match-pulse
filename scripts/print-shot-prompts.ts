import { indiaWicketBalls, indNzCard, indNzMeta } from "../fixtures/ind-nz-2nd-odi-2026";
import { buildMatchStory } from "../src/domain/story";
import { buildShotPlan, resolveShotPrompt } from "../src/domain/shot-plan";
import { createShotDirector } from "../src/providers/story/shot-director";

const story = buildMatchStory({
  meta: indNzMeta,
  deliveries: indiaWicketBalls,
  picks: [],
  card: indNzCard,
});

const names = indNzMeta.players.map((player) => player.name);
const plan = buildShotPlan(story.beats, {
  venue: story.venue,
  chaseTeam: story.team,
  winSeries: story.winSeries,
});

async function main(): Promise<void> {
  const director = createShotDirector();
  const lines = [
    "# Anime shot prompts: New Zealand vs India, 2nd ODI",
    "",
    "Generated by `scripts/print-shot-prompts.ts`. The fact is the sourced beat. The prompt is the template (or a director rewrite that still matches the event). No player names, numbers, or logos go into the prompt.",
    "",
    "## Globals",
    "",
    plan.globals.style,
    "",
    plan.globals.world,
    "",
    plan.globals.characters,
    "",
    plan.globals.constraints,
    "",
  ];
  for (const [index, shot] of plan.shots.entries()) {
    const rendered = await resolveShotPrompt(shot, plan.globals, names, director ?? undefined);
    lines.push(
      `## Shot ${index + 1} — ${shot.event} — ${shot.seconds}s`,
      "",
      `Beat: \`${shot.beatId}\``,
      "",
      `Fact: ${shot.fact}`,
      "",
      `Source: ${rendered.source}`,
      "",
      "### Prompt",
      "",
      "```",
      rendered.prompt,
      "```",
      "",
      "### Negative prompt",
      "",
      "```",
      rendered.negativePrompt,
      "```",
      "",
    );
  }
  process.stdout.write(`${lines.join("\n")}\n`);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
